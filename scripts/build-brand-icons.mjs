// T-181: official platform icons for Connections, taken unchanged from the simple-icons package (CC0; the marks
// themselves remain trademarks of their owners and are used only to name the service being connected).
// Writes saas/brand-icons.js so the live site needs no extra package. Run: npm run build:brand-icons
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const dir = new URL('../node_modules/simple-icons/', import.meta.url);
const data = JSON.parse(fs.readFileSync(new URL('data/simple-icons.json', dir), 'utf8'));
const all = Array.isArray(data) ? data : data.icons;
const pick = (title) => { const i = all.find((x) => x.title === title); if (!i) throw new Error('Missing icon: ' + title); const slug = i.slug || require('simple-icons/sdk').titleToSlug(title); const svg = fs.readFileSync(new URL(`icons/${slug}.svg`, dir), 'utf8'); return { title, hex: '#' + i.hex, path: svg.match(/ d="([^"]+)"/)[1] }; };
// Connection provider id -> official icon(s). Website and Email/SMS are Oprun's own and keep Oprun badges.
const MAP = { meta: ['Facebook', 'Instagram'], facebook: ['Facebook'], instagram: ['Instagram'], whatsapp: ['WhatsApp'], tiktok: ['TikTok'], youtube: ['YouTube'], x: ['X'], snapchat: ['Snapchat'], gmail: ['Gmail'], google_business: ['Google'], google_seo: ['Google Search Console'], zoom: ['Zoom'] };
const icons = {}; for (const titles of Object.values(MAP)) for (const t of titles) icons[t] = pick(t);
const out = `// Generated by scripts/build-brand-icons.mjs from simple-icons ${JSON.parse(fs.readFileSync(new URL('package.json', dir), 'utf8')).version} (CC0). Do not edit.
// Platform names and logos are trademarks of their owners, shown only to identify the service being connected.
window.OprunBrandIcons = ${JSON.stringify({ map: MAP, icons })};
`;
fs.writeFileSync(new URL('../saas/brand-icons.js', import.meta.url), out);
console.log('brand icons:', Object.keys(icons).join(', '));
